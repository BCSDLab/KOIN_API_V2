CREATE TABLE content_translations (
    id VARCHAR(36) NOT NULL,
    cache_key VARCHAR(64) NOT NULL,
    resource_type VARCHAR(32) NOT NULL,
    resource_id VARCHAR(32) NOT NULL,
    parent_id INT NOT NULL,
    room_id INT NOT NULL,
    source_version VARCHAR(64) NOT NULL,
    target_language VARCHAR(35) NOT NULL,
    model VARCHAR(100) NOT NULL,
    prompt_version VARCHAR(20) NOT NULL,
    status VARCHAR(16) NOT NULL,
    translated_json MEDIUMTEXT NULL,
    reason_code VARCHAR(40) NULL,
    owner_token VARCHAR(36) NULL,
    locked_until DATETIME(6) NULL,
    next_attempt_at DATETIME(6) NULL,
    expires_at DATETIME(6) NOT NULL,
    created_at DATETIME(6) NOT NULL,
    updated_at DATETIME(6) NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_content_translations_cache_key UNIQUE (cache_key),
    INDEX idx_content_translations_expires_at (expires_at)
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;
